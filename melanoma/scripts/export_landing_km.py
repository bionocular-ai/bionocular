"""Export the CheckMate 067 PFS digitized twins for the landing page's Survival chart.

Writes landing/data/km-checkmate067-pfs.js as `const KM = {...};`. The landing page has no
database access (CSP connect-src 'self'), so the curves ship as a static file. Re-run this
when the twins change:

    cd melanoma && poetry run python3 scripts/export_landing_km.py
"""

import json
import os
import sys
from pathlib import Path
from typing import Any, cast

from dotenv import load_dotenv
from supabase import create_client

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "landing" / "data" / "km-checkmate067-pfs.js"

MAIN_NCT = "NCT01844505"
MAIN_REF_PREFIX = "N Engl J Med 2019"
MAIN_COMPARISON = "02"
MAIN_ARMS = ("nivolumab_plus_ipilimumab", "nivolumab", "ipilimumab")
# The faint "Scale" curves: one PFS twin each from four other trials.
BG_ARMS = {
    "NCT03470922": "Nivolumab",
    "NCT02908672": "placebo_vemurafenib_cobimetinib",
    "NCT01006980": "vemurafenib",
    "NCT01584648": "dabrafenib_and_trametinib",
}
PFS = ("PFS", "PROGRESSION-FREE SURVIVAL")


def pick(row: dict[str, Any]) -> list[list[float]]:
    return [
        [round(p["time"], 2), round(p["surv"], 1)]
        for p in row["twin_coords"]
        if p["time"] <= 60
    ]


def build(rows: list[dict[str, Any]]) -> dict[str, Any]:
    main_rows = [
        r
        for r in rows
        if r["nct_id"] == MAIN_NCT
        and r["reference"].startswith(MAIN_REF_PREFIX)
        and r["comparison_label"] == MAIN_COMPARISON
        and r["arm_name"] in MAIN_ARMS
    ]
    main = {r["arm_name"]: pick(r) for r in main_rows}
    bg: list[dict[str, Any]] = []
    for nct, arm in BG_ARMS.items():
        row = next(r for r in rows if r["nct_id"] == nct and r["arm_name"] == arm)
        bg.append({"nct": nct, "pts": pick(row)})
    out: dict[str, Any] = {
        "main": {a: main[a] for a in MAIN_ARMS},
        "bg": bg,
        "stored": sum(len(r["twin_coords"]) for r in main_rows),
    }
    # The chart labels the published medians (11.5 / 6.9 / 2.9); the twins must cross 50% near them.
    for arm, published in zip(MAIN_ARMS, (11.5, 6.9, 2.9)):
        crossing = next(t for t, s in out["main"][arm] if s <= 50)
        assert abs(crossing - published) < 0.5, (arm, crossing, published)
    assert len(bg) == 4 and all(b["pts"] for b in bg)
    return out


def main() -> None:
    load_dotenv(ROOT / "melanoma" / ".env")
    url, key = os.environ.get("SUPABASE_URL"), os.environ.get("SUPABASE_KEY")
    if not url or not key:
        sys.exit("ERROR: SUPABASE_URL and SUPABASE_KEY must be set in melanoma/.env.")
    client = create_client(url, key)
    rows = (
        client.table("km_curves")
        .select("nct_id,reference,comparison_label,arm_name,endpoint,twin_coords")
        .in_("endpoint", list(PFS))
        .in_("nct_id", [MAIN_NCT, *BG_ARMS])
        .execute()
        .data
    )
    out = build(cast(list[dict[str, Any]], rows))
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Generated by melanoma/scripts/export_landing_km.py from km_curves. Do not edit by hand.\n"
        f"const KM = {json.dumps(out, separators=(',', ':'))};\n"
    )
    print(
        f"wrote {OUT.relative_to(ROOT)}: stored={out['stored']}, plotted={sum(map(len, out['main'].values()))}"
    )


if __name__ == "__main__":
    main()
